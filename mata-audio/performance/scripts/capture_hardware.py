#!/usr/bin/env python3
"""Capture a portable benchmark-host fingerprint into Markdown."""
from __future__ import annotations
import os, platform, subprocess, sys
from pathlib import Path

out = Path(sys.argv[1] if len(sys.argv) > 1 else "performance/results/hardware-current.md")
out.parent.mkdir(parents=True, exist_ok=True)

def cmd(*args: str) -> str:
    try:
        return subprocess.check_output(args, text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return "unavailable"

def cpu_name() -> str:
    name = platform.processor().strip()
    if name:
        return name
    if Path("/proc/cpuinfo").exists():
        for line in Path("/proc/cpuinfo").read_text(errors="replace").splitlines():
            if line.lower().startswith(("model name", "hardware")) and ":" in line:
                return line.split(":", 1)[1].strip()
    if platform.system() == "Darwin":
        return cmd("sysctl", "-n", "machdep.cpu.brand_string")
    return "unknown"

def memory() -> str:
    if Path("/proc/meminfo").exists():
        for line in Path("/proc/meminfo").read_text(errors="replace").splitlines():
            if line.startswith("MemTotal:"):
                return line.split(":", 1)[1].strip()
    return "unknown"

rustc = cmd("rustc", "--version", "--verbose")
cargo = cmd("cargo", "--version")
n = os.cpu_count() or 0
text = f"""# Pinned benchmark hardware

Generated by `performance/scripts/capture_hardware.py` on the benchmark host.

- Machine / node: {platform.node() or 'unknown'}
- Platform: {platform.platform()}
- OS: {platform.system()} {platform.release()} {platform.version()}
- Architecture: {platform.machine()}
- CPU: {cpu_name()}
- Logical CPUs: {n}
- RAM: {memory()}
- Python: {platform.python_version()}
- Cargo: {cargo}
- Rust compiler:\n```text\n{rustc}\n```
- `RUSTFLAGS`: `{os.environ.get('RUSTFLAGS', '')}`
- `CARGO_BUILD_TARGET`: `{os.environ.get('CARGO_BUILD_TARGET', '')}`
- Notes: record power profile, thermal state, and background-load controls here before accepting the run.
"""
out.write_text(text)
print(out)
